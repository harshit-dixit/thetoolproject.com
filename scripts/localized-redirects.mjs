import assert from 'node:assert/strict';
import { readFileSync, existsSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';
import { localizedPaths } from '../src/data/localized-paths.mjs';
import { historicalPathForms, validateLocalizedPaths } from '../src/data/localized-path-validation.mjs';

export const generatedHeader = '# Generated by scripts/generate-localized-redirects.mjs. Do not edit.\n';
export const projectRoot = fileURLToPath(new URL('../', import.meta.url));

/** Preserve independent rules in a separate input; localized rules have one owner. */
export function parseRedirectSource(source) {
  return source.split(/\r?\n/).flatMap((line, index) => {
    const text = line.trim();
    if (!text || text.startsWith('#')) return [];
    assert.ok(text.length <= 1000, `Redirect source line ${index + 1} exceeds 1,000 characters`);
    const fields = text.split(/\s+/);
    const [from, destination, code = '302'] = fields;
    assert.ok(fields.length >= 2 && fields.length <= 3 && from.startsWith('/') && !from.startsWith('//') && !/[?#]/.test(from),
      `Invalid redirect source line ${index + 1}`);
    assert.ok(destination.startsWith('/') && !destination.startsWith('//') || /^https?:\/\//.test(destination),
      `Invalid redirect destination on line ${index + 1}`);
    assert.ok(['200', '301', '302', '303', '307', '308'].includes(code), `Invalid redirect status on line ${index + 1}`);
    assert.ok((from.match(/\*/g) || []).length <= 1, `Only one splat is supported: ${from}`);
    return [{ source: from, destination, status: Number(code) }];
  });
}

const dynamic = rule => /\*|:[A-Za-z]\w*/.test(rule.source);
const patternFor = rule => {
  // Cloudflare path placeholders match one segment; splats match the remaining path.
  const escaped = rule.source.replace(/[.+?^${}()|[\]\\]/g, '\\$&')
    .replace(/:[A-Za-z]\w*/g, '[^/]+').replace(/\*/g, '.*');
  return new RegExp(`^${escaped}$`);
};

export function renderRedirects(migrationRules, source = '') {
  const independent = parseRedirectSource(source);
  const protectedPaths = new Set(migrationRules.flatMap(rule => [rule.source, ...historicalPathForms(rule.destination)]));
  for (const rule of independent) {
    const pattern = patternFor(rule);
    for (const path of protectedPaths) {
      assert.ok(!pattern.test(path), `Independent redirect overlaps a migration path: ${rule.source} matches ${path}`);
    }
  }
  const rules = [...migrationRules, ...independent];
  const staticRules = rules.filter(rule => !dynamic(rule));
  const dynamicRules = rules.filter(dynamic);
  assert.ok(staticRules.length <= 2000, 'Cloudflare limit exceeded: 2,000 static redirects');
  assert.ok(dynamicRules.length <= 100, 'Cloudflare limit exceeded: 100 dynamic redirects');
  const staticSources = new Set(staticRules.map(rule => rule.source));
  const dynamicPatterns = dynamicRules.map(patternFor);
  const seen = new Set();
  for (const rule of rules) {
    assert.ok(!seen.has(rule.source), `Duplicate redirect source: ${rule.source}`);
    seen.add(rule.source);
    if (rule.status !== 200 && rule.destination.startsWith('/')) {
      const destinationPath = rule.destination.split(/[?#]/)[0];
      assert.ok(!staticSources.has(destinationPath) && !dynamicPatterns.some(pattern => pattern.test(destinationPath)),
        `Redirect chain, loop or self-redirect: ${rule.source} -> ${rule.destination}`);
    }
  }
  const lines = [...staticRules, ...dynamicRules].map(rule => `${rule.source} ${rule.destination} ${rule.status}`);
  assert.ok(lines.every(line => line.length <= 1000), 'Cloudflare redirect declaration exceeds 1,000 characters');
  return generatedHeader + '# Independent rules: scripts/redirects-source.txt; localized rules: src/data/localized-paths.mjs\n'
    + (lines.length ? `${lines.join('\n')}\n` : '# No active redirect rules.\n');
}

/** Load Astro's actual TS registries without duplicating IDs or publication gates. */
export async function loadRoutingRegistries(root = projectRoot) {
  const loader = await createServer({
    root, configFile: false, server: { middlewareMode: true, watch: null },
    appType: 'custom', logLevel: 'error',
  });
  try {
    const { tools } = await loader.ssrLoadModule('/src/data/tools.ts');
    const { sitePages: pages } = await loader.ssrLoadModule('/src/data/pages.ts');
    return { tools, pages };
  } finally {
    await loader.close();
  }
}

export async function generateLocalizedRedirects({ root = projectRoot, check = false, distCheck = false } = {}) {
  const registries = await loadRoutingRegistries(root);
  // The original published paths remain build-time evidence, not runtime routing data.
  const baseline = JSON.parse(readFileSync(join(root, 'docs/localized-url-baseline.json'), 'utf8'));
  assert.ok(Array.isArray(baseline.publishedRoutes), 'Missing published baseline URL evidence');
  const rules = validateLocalizedPaths(localizedPaths, registries, baseline.publishedRoutes);
  const independent = readFileSync(join(root, 'scripts/redirects-source.txt'), 'utf8');
  const expected = renderRedirects(rules, independent);
  const output = join(root, 'public/_redirects');
  if (check || distCheck) {
    assert.equal(readFileSync(output, 'utf8').replaceAll('\r\n', '\n'), expected, 'public/_redirects is stale; regenerate it');
  } else {
    if (existsSync(output)) {
      assert.ok(readFileSync(output, 'utf8').startsWith(generatedHeader.trimEnd()),
        'Preserve existing public/_redirects rules in scripts/redirects-source.txt before generating');
    }
    writeFileSync(output, expected);
  }
  if (distCheck) {
    assert.equal(readFileSync(join(root, 'dist/_redirects'), 'utf8').replaceAll('\r\n', '\n'), expected,
      'dist/_redirects is missing or stale; rebuild');
    for (const destination of new Set(rules.map(rule => rule.destination))) {
      assert.ok(existsSync(join(root, 'dist', destination.slice(1), 'index.html')), `Missing redirect destination: ${destination}`);
    }
    for (const rule of rules.filter(rule => rule.source.endsWith('/'))) {
      assert.ok(!existsSync(join(root, 'dist', rule.source.slice(1), 'index.html')), `Historical alias still emits content: ${rule.source}`);
    }
  }
  return rules;
}
